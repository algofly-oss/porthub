const SESSION_MS: i64 = 180 * 24 * 60 * 60 * 1000;

pub fn token(headers: &HeaderMap, app: &App) -> String {
    headers
        .get_all(header::COOKIE)
        .iter()
        .filter_map(|value| value.to_str().ok())
        .flat_map(|value| value.split(';'))
        .filter_map(|part| part.trim().split_once('='))
        .find(|(key, _)| *key == app.config.session_cookie)
        .map(|(_, value)| value.trim_matches('"').to_owned())
        .unwrap_or_default()
}

fn is_https(headers: &HeaderMap) -> bool {
    headers
        .get("x-forwarded-proto")
        .and_then(|v| v.to_str().ok())
        .is_some_and(|v| v.eq_ignore_ascii_case("https"))
        || headers
            .get("cf-visitor")
            .and_then(|v| v.to_str().ok())
            .and_then(|v| serde_json::from_str::<Value>(v).ok())
            .is_some_and(|v| v["scheme"] == "https")
}

pub(crate) fn cookie(headers: &HeaderMap, app: &App, value: &str, age: i64) -> HeaderValue {
    let secure = if is_https(headers) { "; Secure" } else { "" };
    // Configured cookie names are validated at startup; values here are UUIDs
    // generated by this service (or empty when clearing the cookie).
    HeaderValue::from_str(&format!(
        "{}={value}; Path=/; Max-Age={age}; HttpOnly; SameSite=Lax{secure}",
        app.config.session_cookie
    ))
    .expect("validated cookie name and generated session value")
}

pub(crate) fn with_cookie(body: Value, cookie: HeaderValue) -> Response {
    ([(header::SET_COOKIE, cookie)], Json(body)).into_response()
}

pub async fn user_id(app: &App, token: &str) -> ApiResult<Option<String>> {
    if token.is_empty() || token.len() > 128 {
        return Ok(None);
    }
    let row = app
        .collection("user_sessions")
        .find_one(doc! {"_id": token, "revoked_at": Bson::Null})
        .await?;
    let Some(row) = row else {
        return Ok(None);
    };
    if row
        .get_datetime("expires_at")
        .is_ok_and(|date| date.timestamp_millis() <= DateTime::now().timestamp_millis())
    {
        return Ok(None);
    }
    Ok(row.get_str("user_id").ok().map(str::to_owned))
}

pub async fn current_user(app: &App, headers: &HeaderMap) -> ApiResult<Document> {
    let id = user_id(app, &token(headers, app))
        .await?
        .ok_or_else(ApiError::unauthenticated)?;
    let id = ObjectId::parse_str(id).map_err(|_| ApiError::unauthenticated())?;
    app.collection("users")
        .find_one(doc! {"_id": id})
        .await?
        .ok_or_else(ApiError::unauthenticated)
}

fn str_value<'a>(doc: &'a Document, key: &str, fallback: &'a str) -> &'a str {
    doc.get_str(key)
        .ok()
        .filter(|s| !s.is_empty())
        .unwrap_or(fallback)
}

fn metadata(headers: &HeaderMap) -> Document {
    let ua = headers
        .get(header::USER_AGENT)
        .and_then(|s| s.to_str().ok())
        .unwrap_or("");
    let browser = if ua.contains("Edg/") {
        "Edge"
    } else if ua.contains("Chrome/") && !ua.contains("Chromium/") {
        "Chrome"
    } else if ua.contains("Firefox/") {
        "Firefox"
    } else if ua.contains("Safari/") && !ua.contains("Chrome/") {
        "Safari"
    } else {
        "Unknown browser"
    };
    let os = if ua.contains("Windows") {
        "Windows"
    } else if ua.contains("Mac OS X") || ua.contains("Macintosh") {
        "macOS"
    } else if ua.contains("Android") {
        "Android"
    } else if ua.contains("iPhone") || ua.contains("iPad") {
        "iOS"
    } else if ua.contains("Linux") {
        "Linux"
    } else {
        "Unknown OS"
    };
    let kind = if ua.contains("Mobile") || ua.contains("iPhone") || ua.contains("Android") {
        "Mobile"
    } else if ua.contains("iPad") || ua.contains("Tablet") {
        "Tablet"
    } else {
        "Desktop"
    };
    let ip = [
        "cf-connecting-ip",
        "x-real-ip",
        "x-client-ip",
        "x-forwarded-for",
    ]
    .iter()
    .find_map(|name| headers.get(*name).and_then(|v| v.to_str().ok()))
    .and_then(|v| v.split(',').next())
    .unwrap_or("Unknown IP")
    .trim();
    doc! {"browser": browser, "os": os, "device_type": kind, "device_name": format!("{browser} on {os}"), "ip": ip, "user_agent": ua}
}

pub async fn settings(State(app): State<Arc<App>>) -> crate::error::ApiResult<Json<Value>> {
    let setting = app
        .collection("platform_settings")
        .find_one(mongodb::bson::doc! {"_id":"platform"})
        .await?;
    let signup_enabled = setting
        .as_ref()
        .and_then(|d| d.get_bool("signup_enabled").ok())
        .unwrap_or(!app.config.signup_disabled);
    Ok(Json(
        json!({"signup_disabled": !signup_enabled, "signup_enabled": signup_enabled,
        "web_proxy_domain_suffix": app.config.proxy_domain_suffix, "port_hub_service_domain": app.config.service_domain}),
    ))
}

pub async fn signin(
    State(app): State<Arc<App>>,
    headers: HeaderMap,
    ApiBody(raw): ApiBody,
) -> ApiResult<Response> {
    let mut model = Model::new(raw)?;
    let username = model.required_string("username");
    let password = model.required_string("password");
    model.finish()?;
    if user_id(&app, &token(&headers, &app)).await?.is_some() {
        return Ok(Json(json!({"msg":"success"})).into_response());
    }
    let user = app
        .collection("users")
        .find_one(doc! {"username": &username})
        .await?
        .ok_or_else(|| ApiError::new(StatusCode::BAD_REQUEST, "incorrect username"))?;
    let valid = crate::domain::accounts::verify_password(&user, password).await?;
    if !valid {
        return Err(ApiError::new(StatusCode::BAD_REQUEST, "incorrect password"));
    }
    let id = user
        .get_object_id("_id")
        .map_err(|_| ApiError::unauthenticated())?
        .to_hex();
    let session_cookie = start_session(&app, &headers, &id).await?;
    Ok(with_cookie(json!({"msg":"success"}), session_cookie))
}

pub async fn start_session(app: &App, headers: &HeaderMap, id: &str) -> ApiResult<HeaderValue> {
    let token = uuid::Uuid::new_v4().to_string();
    let now = DateTime::now();
    let mut record = metadata(headers);
    record.extend(doc! {"_id": &token, "token": &token, "user_id": id, "revoked_at": Bson::Null,
        "created_at": now, "last_accessed_at": now, "renewed_at": now, "expires_at": DateTime::from_millis(now.timestamp_millis() + SESSION_MS)});
    app.collection("user_sessions").insert_one(record).await?;
    Ok(cookie(headers, app, &token, SESSION_MS / 1000))
}

pub async fn signout(State(app): State<Arc<App>>, headers: HeaderMap) -> ApiResult<Response> {
    let value = token(&headers, &app);
    if value.is_empty() {
        return Ok(Json(json!({"msg":"user not logged in"})).into_response());
    }
    app.collection("user_sessions")
        .update_one(
            doc! {"_id": &value},
            doc! {"$set":{"revoked_at": DateTime::now()}},
        )
        .await?;
    app.realtime.disconnect_session(&value);
    Ok(with_cookie(
        json!({"msg":"success"}),
        cookie(&headers, &app, "", 0),
    ))
}

pub async fn me(State(app): State<Arc<App>>, headers: HeaderMap) -> ApiResult<Json<Value>> {
    let user = current_user(&app, &headers).await?;
    touch_session(&app, &headers).await?;
    let field = |key: &str| user.get(key).map(store::json).unwrap_or(Value::Null);
    Ok(Json(json!({
        "name":str_value(&user,"name",""), "username":str_value(&user,"username",""),
        "email":str_value(&user,"email",str_value(&user,"username","")), "role":str_value(&user,"role",""),
        "created_at":field("created_at"), "profile_picture":field("profile_picture"),
        "has_password": user.get("password").is_some_and(|p| match p { Bson::Binary(b) => !b.bytes.is_empty(), Bson::String(s) => !s.is_empty(), _ => false }),
        "preferences":{"nav_collapsed":user.get_document("preferences").ok().and_then(|p|p.get_bool("nav_collapsed").ok()).unwrap_or(false)}
    })))
}

async fn touch_session(app: &App, headers: &HeaderMap) -> ApiResult<()> {
    let mut touch = metadata(headers);
    touch.remove("ip");
    touch.insert("last_accessed_at", DateTime::now());
    app.collection("user_sessions")
        .update_one(
            doc! {"_id":token(headers,app),"revoked_at":Bson::Null},
            doc! {"$set":touch},
        )
        .await?;
    Ok(())
}

pub async fn sessions(State(app): State<Arc<App>>, headers: HeaderMap) -> ApiResult<Json<Value>> {
    let user = current_user(&app, &headers).await?;
    touch_session(&app, &headers).await?;
    let id = user
        .get_object_id("_id")
        .map_err(|_| ApiError::unauthenticated())?
        .to_hex();
    let docs: Vec<Document> = app
        .collection("user_sessions")
        .find(doc! {"user_id":id,"revoked_at":Bson::Null})
        .sort(doc! {"last_accessed_at":-1})
        .limit(100)
        .await?
        .try_collect()
        .await?;
    let current = token(&headers, &app);
    let data: Vec<Value> = docs.iter().map(|row| {
        let date = |key| row.get_datetime(key).ok().map(|d| Value::String(format!("{}Z", store::datetime(d.timestamp_millis())))).unwrap_or(Value::Null);
        json!({"id":str_value(row,"_id",""), "current":str_value(row,"_id","")==current,
            "device_name":str_value(row,"device_name","Unknown device"), "device_type":str_value(row,"device_type","Unknown"),
            "browser":str_value(row,"browser","Unknown browser"),"os":str_value(row,"os","Unknown OS"),"ip":str_value(row,"ip","Unknown IP"),
            "created_at":date("created_at"),"last_accessed_at":date("last_accessed_at")})
    }).collect();
    Ok(Json(json!({"data":data})))
}

pub async fn revoke_session(
    State(app): State<Arc<App>>,
    headers: HeaderMap,
    Path(id): Path<String>,
) -> ApiResult<Response> {
    let user = current_user(&app, &headers).await?;
    let user_id = user
        .get_object_id("_id")
        .map_err(|_| ApiError::unauthenticated())?
        .to_hex();
    let result = app
        .collection("user_sessions")
        .update_one(
            doc! {"_id":&id,"user_id":user_id,"revoked_at":Bson::Null},
            doc! {"$set":{"revoked_at":DateTime::now()}},
        )
        .await?;
    if result.matched_count == 0 {
        return Err(ApiError::new(StatusCode::NOT_FOUND, "Session not found"));
    }
    app.realtime.disconnect_session(&id);
    if id == token(&headers, &app) {
        return Ok(with_cookie(
            json!({"msg":"success"}),
            cookie(&headers, &app, "", 0),
        ));
    }
    Ok(Json(json!({"msg":"success"})).into_response())
}

// Slide expiry at most once a day after successful responses without rotating
// existing tokens, preserving sessions issued by the Go API.
pub async fn renew_session(
    State(app): State<Arc<App>>,
    request: axum::extract::Request,
    next: axum::middleware::Next,
) -> Response {
    let headers = request.headers().clone();
    let value = token(&headers, &app);
    let mut response = next.run(request).await;
    if response.status().as_u16() >= 400 || value.is_empty() || value.len() > 128 {
        return response;
    }
    let now = DateTime::now();
    let filter = doc! {"_id":&value,"revoked_at":Bson::Null,"$and":[
        {"$or":[{"expires_at":Bson::Null},{"expires_at":{"$gt":now}}]},
        {"$or":[{"renewed_at":{"$exists":false}},{"renewed_at":{"$lt":DateTime::from_millis(now.timestamp_millis()-86_400_000)}}]}
    ]};
    match app.collection("user_sessions").update_one(filter, doc! {"$set":{
        "renewed_at":now,"expires_at":DateTime::from_millis(now.timestamp_millis()+SESSION_MS)
    }}).await {
        Ok(result) if result.matched_count == 1 => { response.headers_mut().append(header::SET_COOKIE, cookie(&headers,&app,&value,SESSION_MS/1000)); }
        Err(error) => tracing::warn!(%error,"could not renew session"),
        _ => {},
    }
    response
}
