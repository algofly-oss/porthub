const { launchBrowser } = require("./browser.cjs");
const assert = require("node:assert/strict");
(async () => {
  const browser = await launchBrowser();
  try {
    const page = await browser.newPage({ viewport: { width: 1512, height: 982 } });
    const errors = [];
    page.on("pageerror", error => errors.push(error.message));
    await page.goto("http://luna.local/home?demo=1&view=machines");
    await page.getByRole("button", { name: "Groups", exact: true }).click();
    const dialog = page.getByRole("dialog", { name: "Machine Groups", exact: true });
    await dialog.getByLabel("New group name").fill("Review group");
    await dialog.getByRole("button", { name: "Create group", exact: true }).click();
    await page.waitForFunction(() => document.querySelector('[aria-label="Group name"]')?.value === "Review group");
    const machine = dialog.getByRole("checkbox", { name: "Include orion-dev-02", exact: true });
    await machine.check();
    await page.waitForFunction(() => document.querySelector('[aria-label="Include orion-dev-02"]')?.getAttribute("data-state") === "checked");
    await dialog.getByLabel("Group name", { exact: true }).fill("Renamed review group");
    await dialog.getByRole("button", { name: "Save", exact: true }).click();
    await dialog.getByRole("button", { name: /Renamed review group/ }).waitFor();
    await page.screenshot({ path: "/tmp/porthub-groups-desktop.png" });
    await page.keyboard.press("Escape");
    await dialog.waitFor({ state: "hidden" });
    await page.getByLabel("Filter machine group").fill("Renamed review group");
    await page.getByRole("option", { name: "Renamed review group", exact: true }).click();
    assert.equal(await page.getByRole("button", { name: "Configure orion-dev-02", exact: true }).count(), 1);
    await page.reload();
    await page.getByRole("button", { name: "Groups", exact: true }).click();
    await dialog.getByRole("button", { name: /Renamed review group/ }).click();
    assert(await machine.isChecked(), "Membership persists across a reload");
    await page.keyboard.press("Escape");
    await page.setViewportSize({ width: 402, height: 874 });
    await page.getByRole("button", { name: "Groups", exact: true }).click();
    await dialog.waitFor();
    await page.waitForTimeout(400);
    let bounds = await dialog.boundingBox();
    assert(Math.abs(bounds.x) <= 1 && Math.abs(bounds.y + bounds.height - 874) <= 1, `Sheet should touch viewport bottom: ${JSON.stringify(bounds)}`);
    await page.screenshot({ path: "/tmp/porthub-groups-phone.png" });
    await dialog.getByLabel("Choose a group", {exact:true}).fill("Renamed review group");
    await page.getByRole("option", {name:"Renamed review group",exact:true}).click();
    await dialog.getByRole("button", { name: "Delete group", exact: true }).click();
    await dialog.getByRole("button", { name: "Delete group", exact: true }).last().click();
    await page.waitForFunction(() => !JSON.parse(sessionStorage.getItem("porthub-demo-v1")).groups.some(group => group.name === "Renamed review group"));
    await dialog.getByRole("status").filter({ hasText: "Changes save automatically" }).waitFor();
    await page.keyboard.press("Escape");
    await dialog.waitFor({ state: "hidden" });
    await page.getByRole("button", { name: "Configure orion-dev-02", exact: true }).click();
    await page.getByRole("dialog").waitFor();
    await page.waitForTimeout(400);
    await page.screenshot({ path: "/tmp/porthub-machine-sheet.png" });
    await page.keyboard.press("Escape");
    await page.setViewportSize({ width: 1512, height: 982 });
    await page.getByRole("button", { name: "Switch to light theme", exact: true }).click();
    await page.screenshot({ path: "/tmp/porthub-machines-light.png" });
    await page.getByLabel("Search machines", { exact: true }).focus();
    const focus = await page.getByLabel("Search machines", { exact: true }).evaluate(el => ({ outline: getComputedStyle(el).outlineStyle, shadow: getComputedStyle(el).boxShadow }));
    assert.equal(focus.outline, "none");
    assert.equal(focus.shadow, "none");
    assert.deepEqual(errors, []);
    console.log("PASS group create/rename/membership persistence/delete, phone bottom sheets, neutral input focus, and no browser errors");
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
