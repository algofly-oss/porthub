const assert = require('node:assert/strict');
const { readFileSync } = require('node:fs');
const { join } = require('node:path');

(async () => {
  const source = readFileSync(join(__dirname, '../src/lib/terminalDelivery.js'));
  const { InputJournal, OutputJournal, encodePacket, parsePacket, MAX_PAYLOAD, MAX_FRAMES } =
    await import(`data:text/javascript;base64,${source.toString('base64')}`);
  const epoch = 'a'.repeat(32), other = 'b'.repeat(32);
  const input = new InputJournal(epoch), output = new OutputJournal(epoch);
  const first = input.enqueue(new Uint8Array([0, 255, 27]));
  const second = input.enqueue(new Uint8Array([13]));
  assert(output.stage(parsePacket(second)));
  assert.equal(output.next(), null);
  assert(output.stage(parsePacket(first)));
  assert(!output.stage(parsePacket(first)));
  assert.equal(parsePacket(output.acknowledgement()).sequence, 0);
  assert.throws(() => output.commit(2));
  assert.throws(() => output.stage({ ...parsePacket(first), payload: new Uint8Array([9]) }));
  assert.throws(() => input.acknowledge({ kind: 'ack', epoch: other, sequence: 1 }));
  assert.throws(() => input.acknowledge({ kind: 'ack', epoch, sequence: 3 }));
  assert.equal(input.pendingFrames, 2);
  const copy = output.next(); copy.payload.fill(7);
  assert.deepEqual([...output.next().payload], [0, 255, 27]);
  output.commit(1);
  input.acknowledge(parsePacket(output.acknowledgement()));
  assert.equal(input.pendingFrames, 1);
  assert.deepEqual([...input.replay()][0], second);
  output.commit(2);
  input.acknowledge(parsePacket(output.acknowledgement()));
  assert.equal(input.retainedBytes, 0);
  assert.equal(output.retainedBytes, 0);
  assert(!output.stage(parsePacket(first)));
  const full = new InputJournal(epoch), slow = new OutputJournal(epoch);
  for (let i = 0; i < 4; i++) slow.stage(parsePacket(full.enqueue(new Uint8Array(MAX_PAYLOAD))));
  assert.throws(() => full.enqueue(new Uint8Array([1])));
  assert.throws(() => slow.stage({ kind: 'data', epoch, sequence: 5, payload: new Uint8Array([1]) }));
  assert.throws(() => slow.stage({ kind: 'data', epoch, sequence: MAX_FRAMES + 1, payload: new Uint8Array([1]) }));
  assert.throws(() => slow.stage({ kind: 'data', epoch: other, sequence: 1, payload: new Uint8Array([1]) }));
  const tiny = new InputJournal(epoch);
  for (let i = 0; i < MAX_FRAMES; i++) tiny.enqueue(new Uint8Array([1]));
  assert.throws(() => tiny.enqueue(new Uint8Array([1])));
  assert.throws(() => encodePacket({ kind: 'data', epoch, sequence: 0, payload: new Uint8Array([1]) }));
  assert.throws(() => encodePacket({ kind: 'ack', epoch, sequence: 0, payload: new Uint8Array() }));
  assert.throws(() => parsePacket(first.subarray(0, 24)));
  const unsafe = first.slice(); new DataView(unsafe.buffer).setBigUint64(17, 2n ** 53n);
  assert.throws(() => parsePacket(unsafe));
  const padded = new Uint8Array(first.length + 4); padded.set(first, 2);
  assert.deepEqual(parsePacket(padded.subarray(2, -2)), parsePacket(first));
  assert.equal(Buffer.from(first).toString('hex'), `01${epoch}000000000000000100ff1b`);
  console.log('PASS terminal delivery: bounded journals, commit-before-ACK, path replay, epochs and binary framing');
})().catch(error => { console.error(error); process.exitCode = 1; });
