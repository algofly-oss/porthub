const { launchBrowser } = require("./browser.cjs");
const assert = require("node:assert/strict");

(async () => {
  const browser = await launchBrowser();
  try {
    const page = await browser.newPage({ viewport: { width: 1512, height: 982 } });
    const errors = [], realApiRequests = [];
    page.on("pageerror", error => errors.push(error.message));
    page.on("request", request => { if (new URL(request.url()).pathname.startsWith("/api/")) realApiRequests.push(request.url()); });
    await page.goto("http://luna.local/home?demo=1");
    await page.getByRole("heading", { name: "Dashboard", exact: true }).waitFor();
    const outgoing = page.getByRole("button", {name:"Outgoing",exact:true});
    await outgoing.click();
    assert.equal(await outgoing.getAttribute("aria-pressed"), "false");
    await outgoing.click();
    await page.getByRole("button", {name:/^Online\s*\d+/}).click();
    assert.match(page.url(), /view=machines/);
    await page.getByRole("button", {name:"Configure orion-dev-02",exact:true}).click();
    const machine = page.getByRole("dialog", {name:/^Configure orion-dev-02/});
    await machine.waitFor();
    await page.waitForTimeout(200);
    const bounds = await machine.boundingBox();
    assert.equal(await machine.getByRole("table", {name:"Forwarded ports",exact:true}).getByRole("row").count(), 3);
    assert.equal(await machine.getByLabel(/^.+port traffic:/).count(), 2);
    await machine.getByRole("link", {name:"orion-dev-02.preview.invalid",exact:true}).waitFor();
    for (const section of ["Details","Client","Logs","History","Ports"]) {
      await machine.getByRole("button", {name:section,exact:true}).click();
      assert.equal(Math.round((await machine.boundingBox()).height), Math.round(bounds.height));
    }
    await machine.getByRole("button", {name:"Edit forwarding rule API",exact:true}).click();
    await machine.getByRole("button", {name:"Access",exact:true}).click();
    await machine.getByLabel("Allowed source IP", {exact:true}).fill("192.0.2.42");
    await machine.getByRole("button", {name:"Add IP",exact:true}).click();
    await machine.getByRole("button", {name:"Remove 192.0.2.42",exact:true}).waitFor();
    await machine.getByRole("button", {name:"Web Addresses",exact:true}).click();
    await machine.getByRole("button", {name:"Edit proxy orion-dev-02.preview.invalid",exact:true}).click();
    const proxy = page.getByRole("dialog", {name:/^Edit Proxy Route/});
    await proxy.getByRole("button", {name:"Options",exact:true}).click();
    await proxy.getByLabel("Proxy group", {exact:true}).fill("Port context review");
    await proxy.getByRole("button", {name:"Save Proxy",exact:true}).click();
    await proxy.waitFor({state:"hidden"});
    await machine.getByRole("button", {name:"Cancel",exact:true}).click();
    await machine.getByRole("button", {name:"Close",exact:true}).click();
    await machine.waitFor({state:"hidden"});
    await page.getByRole("button", {name:"Proxies",exact:true}).click();
    await page.getByRole("button", {name:"Create proxy",exact:true}).click();
    const create = page.getByRole("dialog", {name:"Create Proxy Route",exact:true});
    await create.getByLabel("Primary subdomain", {exact:true}).fill("workflow-review");
    await create.getByLabel("Domain suffix", {exact:true}).fill("preview.invalid");
    await create.getByRole("button", {name:"Continue",exact:true}).click();
    await create.getByRole("button", {name:"Standalone URL",exact:true}).click();
    await create.getByLabel("Target URL", {exact:true}).fill("http://192.0.2.10:8080");
    await create.getByRole("button", {name:"Continue",exact:true}).click();
    await create.getByLabel("Proxy group", {exact:true}).fill("Standalone review");
    await create.getByRole("button", {name:"Create Proxy",exact:true}).click();
    await create.waitFor({state:"hidden"});
    await page.getByLabel("Search proxies", {exact:true}).fill("workflow-review");
    await page.getByRole("button", {name:"Edit proxy workflow-review.preview.invalid",exact:true}).waitFor();
    await page.reload();
    await page.getByLabel("Search proxies", {exact:true}).fill("workflow-review");
    await page.getByRole("button", {name:"Edit proxy workflow-review.preview.invalid",exact:true}).click();
    await proxy.getByRole("button", {name:"Destination",exact:true}).click();
    assert.equal(await proxy.getByLabel("Target URL", {exact:true}).inputValue(), "http://192.0.2.10:8080");
    await page.keyboard.press("Escape");
    await proxy.waitFor({state:"hidden"});
    await page.getByRole("button", {name:"Settings",exact:true}).click();
    await page.getByLabel("Display name", {exact:true}).fill("Reviewed Workspace");
    await page.getByRole("button", {name:"Save Profile",exact:true}).click();
    await page.getByText("Account updated.", {exact:true}).waitFor();
    await page.reload();
    await page.waitForFunction(() => document.querySelector('input[autocomplete="name"]')?.value === "Reviewed Workspace");
    assert.equal(await page.getByLabel("Display name", {exact:true}).inputValue(), "Reviewed Workspace");
    await page.getByRole("button", {name:"Notifications",exact:true}).click();
    await page.getByLabel("Bot token", {exact:true}).fill("123456789:fake-demo-token");
    await page.getByLabel("Telegram recipient 1", {exact:true}).fill("123456789");
    await page.getByRole("switch", {name:"Enable Telegram alerts",exact:true}).click();
    await page.getByRole("button", {name:"Save Notifications",exact:true}).click();
    await page.getByText("Telegram alert settings updated.", {exact:true}).waitFor();
    await page.reload();
    await page.getByRole("button", {name:"Notifications",exact:true}).click();
    assert.equal(await page.getByRole("switch", {name:"Enable Telegram alerts",exact:true}).getAttribute("aria-checked"), "true");
    assert.equal(await page.getByLabel("Telegram recipient 1", {exact:true}).inputValue(), "123456789");
    assert.deepEqual(realApiRequests, []);
    assert.deepEqual(errors, []);
    console.log("PASS dashboard drill-down, all-port overview, fixed popup height, access editing, contextual proxy editing, standalone proxy creation/persistence, profile and notification settings, API isolation");
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
